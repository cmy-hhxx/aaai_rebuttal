import sys, json, random, string
from typing import List, Tuple, Dict, Any, Optional

# ----------------------------
# Utilities
# ----------------------------

def alpha_index(ch: str) -> int:
    """a->1, b->2 ... z->26; assumes lowercase letter."""
    return ord(ch) - ord('a') + 1

def lex_sort(words: List[str]) -> List[str]:
    return sorted(words, key=lambda w: w.lower())

def first_diff(a: List[str], b: List[str]) -> Optional[int]:
    """Return first index where lists differ, else None."""
    n = min(len(a), len(b))
    for i in range(n):
        if a[i] != b[i]:
            return i
    if len(a) != len(b):
        return n
    return None

def find_first_wrong_step(words: List[str], steps: List[Dict[str, Any]]) -> Optional[int]:
    """
    Validate each step against rules of alphabetic sorting process.
    Return 1-based step index of first wrong step, or None if all steps consistent.
    Steps are generated by our own generator; validator is independent.
    """
    # Model: each step either reports "letters" of a group, or reports a "current ordering string/list".
    # We check:
    # 1) Reported letter positions match actual letters.
    # 2) Any asserted ordering between adjacent blocks must be correct based on lexicographic comparison
    #    of any word in left block vs any word in right block (i.e., all left < all right).
    # 3) No missing/extra words in the "current ordering".
    universe = list(words)

    def normalize_group(g):
        # group can be str or list
        if isinstance(g, str):
            return [g]
        return list(g)

    def flatten(ordering):
        out = []
        for item in ordering:
            out.extend(normalize_group(item))
        return out

    def all_lt(groupA, groupB) -> bool:
        for x in groupA:
            for y in groupB:
                if not (x.lower() < y.lower()):
                    return False
        return True

    current_ordering = None

    for idx, st in enumerate(steps, start=1):
        typ = st.get("type")
        if typ == "letters":
            pos = st["pos"]  # 1-based position
            entries = st["entries"]  # list of (word, reported_letter, reported_index)
            for (w, rep_ch, rep_i) in entries:
                if w not in universe:
                    return idx
                wl = w.lower()
                if pos < 1 or pos > len(wl):
                    # position out of range -> wrong
                    return idx
                true_ch = wl[pos - 1]
                true_i = alpha_index(true_ch)
                if rep_ch != true_ch or rep_i != true_i:
                    return idx

        elif typ == "ordering":
            ordering = st["ordering"]
            flat = flatten(ordering)

            # Check same multiset as universe
            if sorted(flat) != sorted(universe):
                return idx

            # Check adjacent block ordering validity
            for i in range(len(ordering) - 1):
                left = normalize_group(ordering[i])
                right = normalize_group(ordering[i + 1])
                if not all_lt(left, right):
                    return idx

            current_ordering = ordering

        elif typ == "final":
            # final list
            final_list = st["final"]
            if sorted(final_list) != sorted(universe):
                return idx
            # must be exactly sorted lexicographically
            if final_list != lex_sort(universe):
                return idx
        else:
            return idx

    return None


