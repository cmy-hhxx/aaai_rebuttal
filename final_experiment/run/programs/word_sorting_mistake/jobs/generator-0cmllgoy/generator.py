def rand_word(rng: random.Random, min_len=5, max_len=14) -> str:
    # Generate pronounceable-ish lowercase word
    vowels = "aeiou"
    cons = "".join([c for c in string.ascii_lowercase if c not in vowels])
    L = rng.randint(min_len, max_len)
    s = []
    # start with consonant or vowel
    use_vowel = rng.random() < 0.35
    for _ in range(L):
        if use_vowel:
            s.append(rng.choice(vowels))
        else:
            s.append(rng.choice(cons))
        # toggle with some probability
        if rng.random() < 0.8:
            use_vowel = not use_vowel
    w = "".join(s)
    # avoid too many repeats, ensure starts with letter
    return w

def make_unique_words(rng: random.Random, n: int) -> List[str]:
    seen = set()
    words = []
    tries = 0
    while len(words) < n and tries < 5000:
        tries += 1
        w = rand_word(rng)
        if w in seen:
            continue
        seen.add(w)
        words.append(w)
    if len(words) < n:
        raise RuntimeError("无法生成足够唯一单词")
    return words

def force_prefix_collisions(rng: random.Random, words: List[str]) -> List[str]:
    """
    Modify some words to share first letter / first two letters to create interesting sublists.
    Keeps uniqueness.
    """
    words = [w.lower() for w in words]
    n = len(words)
    if n < 8:
        return words

    # pick 2-3 collision groups
    k = rng.randint(2, 3)
    used = set(words)

    for _ in range(k):
        group_size = rng.randint(2, min(4, n // 2))
        idxs = rng.sample(range(n), group_size)
        base = words[idxs[0]]
        # choose collision prefix length 1 or 2
        plen = 1 if rng.random() < 0.55 else 2
        pref = base[:plen]
        for j in idxs[1:]:
            # replace prefix, keep rest
            rest = words[j][plen:]
            cand = pref + rest
            # adjust if collision/duplicate
            tweak_tries = 0
            while cand in used and tweak_tries < 50:
                tweak_tries += 1
                # change one char in rest
                if len(rest) == 0:
                    rest = rng.choice(string.ascii_lowercase)
                pos = rng.randrange(len(rest))
                rest = rest[:pos] + rng.choice(string.ascii_lowercase) + rest[pos+1:]
                cand = pref + rest
            if cand in used:
                continue
            used.remove(words[j])
            words[j] = cand
            used.add(cand)

    return words

