def render_problem(words: List[str], steps: List[Dict[str, Any]]) -> str:
    words_str = " ".join(words)

    lines = []
    lines.append("你是单词排序专家。你将获得一个单词列表和以思考形式呈现的排序步骤，这些步骤试图将单词按字母顺序排列。")
    lines.append("你的任务是找出推理过程中的第一个错误步骤。错误可能包括对字母表顺序的误解、错误理解单词或字母、或遗漏/篡改某个单词。")
    lines.append(f"问题：按字母顺序排列以下单词：{words_str}")

    # Render steps
    step_no = 1
    for st in steps:
        typ = st["type"]
        if typ == "letters":
            pos = st["pos"]
            entries = st["entries"]
            pos_name = {1: "第一个", 2: "第二个", 3: "第三个", 4: "第四个"}.get(pos, f"第{pos}个")
            lines.append(f"思考 {step_no}: 我应该先看相关单词的{pos_name}字母。")
            # list them
            parts = []
            for (w, ch, idxi) in entries:
                if idxi == 27 and ch == "{":
                    parts.append(f"\"{w}\": 超出长度")
                else:
                    parts.append(f"\"{w}\": \"{ch}\" ({idxi})")
            lines.append(" ".join(parts))
        elif typ == "ordering":
            ordering = st["ordering"]
            # format ordering with groups in brackets and < between blocks
            blocks = []
            for item in ordering:
                if isinstance(item, list):
                    blocks.append("[" + " ? ".join([f"\"{w}\"" for w in item]) + "]")
                else:
                    blocks.append(f"\"{item}\"")
            lines.append(f"思考 {step_no}: 我们现在有: " + " < ".join(blocks) + "。")
        elif typ == "final":
            final_list = st["final"]
            lines.append(f"思考 {step_no}: 我已经排序了所有单词。答案是" +
                         "<".join([f"\"{w}\"" for w in final_list]) + "。")
        else:
            lines.append(f"思考 {step_no}: （未知步骤类型）")
        step_no += 1

    lines.append("这个排序过程中有错误吗？如果没有错误，请回答No；如果有错误，请写出第一个错误出现在第几个思考步骤。")
    return "\n".join(lines)

def render_explanation(words: List[str], steps: List[Dict[str, Any]], first_error_step: int) -> str:
    # Provide concrete, checkable reason: compare the faulty step statement with true fact.
    st = steps[first_error_step - 1]
    if st["type"] == "letters":
        pos = st["pos"]
        entries = st["entries"]
        # find an entry that is wrong by direct check
        for (w, rep_ch, rep_i) in entries:
            wl = w.lower()
            if pos > len(wl):
                true_ch, true_i = None, None
                # our validator would treat this as wrong unless explicitly "超出长度" scheme,
                # but we don't use that in corruption.
            else:
                true_ch = wl[pos - 1]
                true_i = alpha_index(true_ch)
                if rep_ch != true_ch or rep_i != true_i:
                    return (
                        f"第一个错误在思考 {first_error_step}：对单词“{w}”的第{pos}个字母记录有误。"
                        f"题面该步写为 {rep_ch} ({rep_i})，但实际第{pos}个字母是 {true_ch} ({true_i})。"
                    )
        return f"第一个错误在思考 {first_error_step}：该步的字母/序号与实际不一致。"

    if st["type"] == "ordering":
        ordering = st["ordering"]

        def normalize_group(g):
            return g if isinstance(g, list) else [g]

        # find first adjacent violation and cite a witness pair
        for i in range(len(ordering) - 1):
            left = normalize_group(ordering[i])
            right = normalize_group(ordering[i + 1])
            for x in left:
                for y in right:
                    if not (x.lower() < y.lower()):
                        return (
                            f"第一个错误在思考 {first_error_step}：该步断言 {left} < {right}，但不成立。"
                            f"例如“{x}”并不小于“{y}”（按字母序应有“{y}”在“{x}”之前）。"
                        )
        return f"第一个错误在思考 {first_error_step}：该步给出的部分顺序与真实字母序不一致。"

    if st["type"] == "final":
        true_sorted = lex_sort(words)
        given = st["final"]
        # locate first inversion
        for i in range(min(len(true_sorted), len(given))):
            if true_sorted[i] != given[i]:
                return (
                    f"第一个错误在思考 {first_error_step}：最终序列不正确。"
                    f"按字母序第{i+1}个应为“{true_sorted[i]}”，但该步给出“{given[i]}”。"
                )
        return f"第一个错误在思考 {first_error_step}：最终序列与正确字母序不一致。"

    return f"第一个错误在思考 {first_error_step}。"


