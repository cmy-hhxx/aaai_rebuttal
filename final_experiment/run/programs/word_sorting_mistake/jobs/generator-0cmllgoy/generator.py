def build_steps_with_one_error(rng: random.Random, words: List[str]) -> Tuple[List[Dict[str, Any]], int]:
    """
    Construct a chain-of-thought-like list of "思考步骤" with exactly one first error.
    Return (steps, first_error_step_index).
    We deliberately introduce one error at a chosen step type.
    """
    words = [w.lower() for w in words]
    correct_sorted = lex_sort(words)

    # Step plan:
    # 1) letters pos=1 for all words
    # 2) ordering by first letter groups (ties grouped)
    # 3) letters pos=2 for a chosen tied group
    # 4) ordering refined for that group (others same)
    # 5) letters pos=2 for another tied group (or pos=3 if needed)
    # 6) ordering refined
    # 7) final
    #
    # We'll inject an error in one of these steps: (letters report wrong char/index),
    # or (ordering puts blocks in wrong order), or (misspells word in ordering), or (final wrong).
    # Then the answer is the first erroneous step number.

    # Helpers to create group ordering by prefix position
    def group_by_first_letter(ws: List[str]) -> List[Any]:
        buckets: Dict[str, List[str]] = {}
        for w in ws:
            buckets.setdefault(w[0], []).append(w)
        ordering = []
        for ch in sorted(buckets.keys()):
            group = sorted(buckets[ch])
            if len(group) == 1:
                ordering.append(group[0])
            else:
                ordering.append(group)
        return ordering

    def refine_group(ordering: List[Any], target_group: List[str], pos: int) -> List[Any]:
        """Refine a specific group by sorting within it using pos-th letter, stable fallback lex."""
        # Sorting key: letter at pos if exists else '{' (after 'z'), then whole word
        def key(w):
            wl = w
            ch = wl[pos-1] if pos <= len(wl) else '{'
            return (ch, wl)
        refined = sorted(target_group, key=key)
        new_order = []
        for item in ordering:
            if isinstance(item, list) and sorted(item) == sorted(target_group):
                # keep as group if still ties on pos
                # check ties based on pos-th char
                chars = [w[pos-1] if pos <= len(w) else '{' for w in refined]
                if len(set(chars)) == 1 and len(refined) > 1:
                    new_order.append(refined)
                else:
                    # expand
                    new_order.extend(refined)
            else:
                new_order.append(item)
        return new_order

    # Create baseline correct steps (no error), then corrupt one step.
    steps: List[Dict[str, Any]] = []

    # Step 1: first letters
    entries1 = []
    for w in words:
        ch = w[0]
        entries1.append((w, ch, alpha_index(ch)))
    steps.append({"type": "letters", "pos": 1, "entries": entries1})

    # Step 2: ordering by first letter groups
    ordering2 = group_by_first_letter(words)
    steps.append({"type": "ordering", "ordering": ordering2})

    # find a group with size>=2 to refine
    groups = [item for item in ordering2 if isinstance(item, list) and len(item) >= 2]
    if not groups:
        # ensure at least one collision by forcing and recompute
        words2 = force_prefix_collisions(rng, words)
        correct_sorted = lex_sort(words2)
        words = words2
        # rebuild step1/2 correctly
        steps = []
        entries1 = []
        for w in words:
            ch = w[0]
            entries1.append((w, ch, alpha_index(ch)))
        steps.append({"type": "letters", "pos": 1, "entries": entries1})
        ordering2 = group_by_first_letter(words)
        steps.append({"type": "ordering", "ordering": ordering2})
        groups = [item for item in ordering2 if isinstance(item, list) and len(item) >= 2]
        if not groups:
            # as last resort, just do final step error-free and inject error elsewhere
            groups = []

    # Choose target groups for refinement
    ordering = ordering2
    pos_ref = 2

    chosen_groups = []
    if groups:
        chosen_groups.append(rng.choice(groups))
        # maybe choose second different group
        other = [g for g in groups if sorted(g) != sorted(chosen_groups[0])]
        if other and rng.random() < 0.7:
            chosen_groups.append(rng.choice(other))

    # Step 3/4 for first chosen group
    if chosen_groups:
        g1 = chosen_groups[0]
        entries3 = []
        for w in g1:
            ch = w[pos_ref-1] if pos_ref <= len(w) else '{'
            rep_i = alpha_index(ch) if ch != '{' else 27
            entries3.append((w, ch, rep_i))
        steps.append({"type": "letters", "pos": pos_ref, "entries": entries3})
        ordering = refine_group(ordering, g1, pos_ref)
        steps.append({"type": "ordering", "ordering": ordering})

    # Step 5/6 for second chosen group (or refine same group at pos=3 if still grouped)
    if len(chosen_groups) >= 2:
        g2 = chosen_groups[1]
        entries5 = []
        for w in g2:
            ch = w[pos_ref-1] if pos_ref <= len(w) else '{'
            rep_i = alpha_index(ch) if ch != '{' else 27
            entries5.append((w, ch, rep_i))
        steps.append({"type": "letters", "pos": pos_ref, "entries": entries5})
        ordering = refine_group(ordering, g2, pos_ref)
        steps.append({"type": "ordering", "ordering": ordering})
    else:
        # if some group remains as list, refine it further at pos=3
        remaining_groups = [item for item in ordering if isinstance(item, list) and len(item) >= 2]
        if remaining_groups:
            g = rng.choice(remaining_groups)
            pos2 = 3
            entries5 = []
            for w in g:
                ch = w[pos2-1] if pos2 <= len(w) else '{'
                rep_i = alpha_index(ch) if ch != '{' else 27
                entries5.append((w, ch, rep_i))
            steps.append({"type": "letters", "pos": pos2, "entries": entries5})
            ordering = refine_group(ordering, g, pos2)
            steps.append({"type": "ordering", "ordering": ordering})

    # Step final: provide final sorted list
    steps.append({"type": "final", "final": correct_sorted})

    # Now inject a single error: pick a step index among existing steps.
    # We must ensure it's the FIRST error: so we only corrupt one step and keep others correct.
    err_step = rng.randrange(1, len(steps) + 1)  # 1-based
    corrupted = json.loads(json.dumps(steps))  # deep copy via json

    typ = corrupted[err_step - 1]["type"]
    if typ == "letters":
        # corrupt one reported letter or its index
        ent = corrupted[err_step - 1]["entries"]
        pick = rng.randrange(len(ent))
        w, ch, idxi = ent[pick]
        # 50% wrong letter, 50% wrong index
        if rng.random() < 0.5:
            wrong_ch = ch
            while wrong_ch == ch:
                wrong_ch = rng.choice(string.ascii_lowercase)
            ent[pick] = (w, wrong_ch, alpha_index(wrong_ch))
        else:
            wrong_i = idxi
            while wrong_i == idxi:
                wrong_i = rng.randint(1, 26)
            ent[pick] = (w, ch, wrong_i)
        corrupted[err_step - 1]["entries"] = ent

    elif typ == "ordering":
        ordering = corrupted[err_step - 1]["ordering"]
        # pick two adjacent blocks and swap them to violate ordering (try).
        if len(ordering) >= 2:
            i = rng.randrange(len(ordering) - 1)
            ordering[i], ordering[i+1] = ordering[i+1], ordering[i]
            corrupted[err_step - 1]["ordering"] = ordering
        else:
            # fallback: misspell a word
            corrupted[err_step - 1]["ordering"] = ["zzzznotaword"]

    elif typ == "final":
        final_list = corrupted[err_step - 1]["final"]
        # swap two elements
        if len(final_list) >= 2:
            i, j = rng.sample(range(len(final_list)), 2)
            final_list[i], final_list[j] = final_list[j], final_list[i]
        corrupted[err_step - 1]["final"] = final_list

    # Validate: first wrong step should be err_step
    first_wrong = find_first_wrong_step(words, corrupted)
    if first_wrong != err_step:
        # If not, try a few times with different corruption modes/step.
        for _ in range(30):
            err_step = rng.randrange(1, len(steps) + 1)
            corrupted = json.loads(json.dumps(steps))
            typ = corrupted[err_step - 1]["type"]
            if typ == "letters":
                ent = corrupted[err_step - 1]["entries"]
                pick = rng.randrange(len(ent))
                w, ch, idxi = ent[pick]
                wrong_ch = ch
                while wrong_ch == ch:
                    wrong_ch = rng.choice(string.ascii_lowercase)
                ent[pick] = (w, wrong_ch, alpha_index(wrong_ch))
                corrupted[err_step - 1]["entries"] = ent
            elif typ == "ordering":
                ordering = corrupted[err_step - 1]["ordering"]
                if len(ordering) >= 2:
                    i = rng.randrange(len(ordering) - 1)
                    ordering[i], ordering[i+1] = ordering[i+1], ordering[i]
                    corrupted[err_step - 1]["ordering"] = ordering
                else:
                    continue
            else:  # final
                final_list = corrupted[err_step - 1]["final"]
                if len(final_list) >= 2:
                    i, j = 0, 1
                    final_list[i], final_list[j] = final_list[j], final_list[i]
                    corrupted[err_step - 1]["final"] = final_list
                else:
                    continue

            first_wrong = find_first_wrong_step(words, corrupted)
            if first_wrong == err_step:
                return corrupted, err_step

        raise RuntimeError("无法稳定构造“第一个错误步骤”一致的实例")

    return corrupted, err_step


