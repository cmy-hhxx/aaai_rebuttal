def generate_one(rng: random.Random) -> Dict[str, Any]:
    # Size varies
    n = rng.randint(10, 16)
    words = make_unique_words(rng, n)
    words = force_prefix_collisions(rng, words)

    steps, err_step = build_steps_with_one_error(rng, words)

    # Cross-check independently:
    first_wrong = find_first_wrong_step(words, steps)
    if first_wrong != err_step:
        raise RuntimeError("内部校验失败：首个错误步骤不一致")

    problem = render_problem(words, steps)
    explanation = render_explanation(words, steps, err_step)
    answer: Any = err_step  # as in seed: return step number, not "No"

    return {"problem": problem, "answer": answer, "explanation": explanation}

def main():
    data = sys.stdin.read()
    try:
        req = json.loads(data)
        seed = int(req["seed"])
        count = int(req["count"])
        if count <= 0:
            raise ValueError
    except Exception:
        print("输入必须是JSON：{\"seed\": 整数, \"count\": 正整数}", file=sys.stderr)
        sys.exit(1)

    rng = random.Random(seed)

    out = []
    seen = set()
    attempts = 0
    # resample with cap to avoid infinite loops
    while len(out) < count and attempts < count * 50:
        attempts += 1
        item = generate_one(rng)
        sig = item["problem"]
        if sig in seen:
            continue
        seen.add(sig)
        out.append(item)

    if len(out) < count:
        print(f"生成失败：仅生成{len(out)}/{count}道不重复题目", file=sys.stderr)
        sys.exit(2)

    sys.stdout.write(json.dumps(out, ensure_ascii=False, indent=2))

if __name__ == "__main__":
    main()